import { useEffect, useRef, useState } from "react";
import {
  Alert, AlertTitle, Box, Button, Card, CardContent, Chip, Divider, LinearProgress, Stack, Tooltip, Typography,
} from "@mui/material";
import AutoAwesomeIcon from "@mui/icons-material/AutoAwesome";
import RefreshIcon from "@mui/icons-material/Refresh";
import { api } from "../api.js";

const POLL_MS = 5000;

// AI-generated profile from a local Ollama model. Generation runs in a background job on the server and takes
// a few minutes on CPU, so this polls until the summary is ready.
export default function SummaryCard({ id }) {
  const [summary, setSummary] = useState(null);
  const [error, setError] = useState(null);
  const [now, setNow] = useState(Date.now());
  const timer = useRef(null);

  const load = (fetcher = api.summary) => {
    clearTimeout(timer.current);
    fetcher(id)
      .then((data) => {
        setSummary(data);
        setError(null);
        if (data.status === "pending" || data.status === "running") timer.current = setTimeout(() => load(), POLL_MS);
      })
      .catch((err) => setError(err));
  };

  useEffect(() => {
    setSummary(null);
    setError(null);
    load();
    const tick = setInterval(() => setNow(Date.now()), 1000);
    return () => {
      clearTimeout(timer.current);
      clearInterval(tick);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [id]);

  const regenerate = () => {
    setSummary((s) => (s ? { ...s, status: "pending", started_at: new Date().toISOString() } : s));
    load(api.regenerateSummary);
  };

  const inProgress = summary && (summary.status === "pending" || summary.status === "running");
  const content = summary?.content;

  return (
    <Card variant="outlined" sx={{ mb: 3 }}>
      <CardContent>
        <Stack direction="row" spacing={1} sx={{ alignItems: "center", mb: 2 }}>
          <AutoAwesomeIcon color="primary" />
          <Typography variant="h6" sx={{ flex: 1 }}>AI summary</Typography>
          {summary?.status === "complete" && !summary.stale && (
            <Button size="small" startIcon={<RefreshIcon />} onClick={regenerate}>Regenerate</Button>
          )}
        </Stack>

        {error && (
          <Alert severity="error" action={<Button color="inherit" size="small" onClick={() => load()}>Retry</Button>}>
            {error.message}
          </Alert>
        )}

        {!summary && !error && <LinearProgress />}

        {inProgress && <Progress summary={summary} now={now} hasContent={!!content} />}

        {summary?.status === "failed" && (
          <Alert severity="warning" action={<Button color="inherit" size="small" onClick={regenerate}>Retry</Button>} sx={{ mb: content ? 2 : 0 }}>
            <AlertTitle>Couldn't generate a summary</AlertTitle>
            {summary.error || "The local model didn't return a usable summary."}
          </Alert>
        )}

        {content && summary.stale && !inProgress && (
          <Alert severity="info" sx={{ mb: 2 }}
            action={<Button color="inherit" size="small" onClick={regenerate}>Regenerate</Button>}>
            This member's votes or bills have been updated since this summary was written.
          </Alert>
        )}

        {content && <SummaryContent content={content} />}

        {content && summary.generated_at && (
          <>
            <Divider sx={{ my: 2 }} />
            <Typography variant="caption" color="text.secondary" component="p">
              Generated by <strong>{summary.model}</strong> running locally, from this app's synced votes, bills and committee data
              on {new Date(summary.generated_at).toLocaleString()}
              {summary.stats?.total_seconds && <> · took {Math.round(summary.stats.total_seconds)}s</>}
              {summary.stats?.prompt_tokens && <> · {summary.stats.prompt_tokens} tokens in, {summary.stats.output_tokens} out</>}.
              AI summaries can contain mistakes; check the evidence in the tabs below.
            </Typography>
          </>
        )}
      </CardContent>
    </Card>
  );
}

function Progress({ summary, now, hasContent }) {
  const elapsed = summary.started_at ? Math.max(0, Math.round((now - new Date(summary.started_at)) / 1000)) : 0;
  const clock = `${Math.floor(elapsed / 60)}:${String(elapsed % 60).padStart(2, "0")}`;
  return (
    <Box sx={{ mb: hasContent ? 2 : 0 }}>
      <LinearProgress sx={{ mb: 1 }} />
      <Typography variant="body2" color="text.secondary">
        {hasContent ? "Generating a new summary" : "Generating a summary"} with a local
        model ({summary.status === "pending" ? "queued" : "running"}, {clock} elapsed). On this computer it usually takes 3–6 minutes;
        you can keep browsing and come back.
      </Typography>
    </Box>
  );
}

function SummaryContent({ content }) {
  return (
    <>
      <Typography sx={{ mb: 2 }}>{content.overview}</Typography>

      {content.key_issues?.length > 0 && (
        <Box sx={{ display: "grid", gap: 1.5, gridTemplateColumns: { xs: "minmax(0, 1fr)", md: "repeat(2, minmax(0, 1fr))" }, mb: 2 }}>
          {content.key_issues.map((issue, i) => (
            <Box key={i} sx={{ p: 1.5, borderRadius: 2, bgcolor: "action.hover" }}>
              <Typography fontWeight={700}>{issue.topic}</Typography>
              <Typography variant="body2" sx={{ my: 0.5 }}>{issue.summary}</Typography>
              <Stack direction="row" sx={{ flexWrap: "wrap", gap: 0.5 }}>
                {(issue.evidence || []).map((e, j) => (
                  <Tooltip key={j} title={e}>
                    <Chip label={e} size="small" variant="outlined" sx={{ maxWidth: "100%" }} />
                  </Tooltip>
                ))}
              </Stack>
            </Box>
          ))}
        </Box>
      )}

      {content.voting_pattern && (
        <Typography variant="body2" sx={{ mb: 1 }}><strong>Voting pattern:</strong> {content.voting_pattern}</Typography>
      )}
      {content.limitations && (
        <Typography variant="body2" color="text.secondary"><strong>Limitations:</strong> {content.limitations}</Typography>
      )}
    </>
  );
}
